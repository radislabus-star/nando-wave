#!/usr/bin/env bash
set -euo pipefail

ENV_FILE="${1:-/etc/nando-wave/phase-center.env}"
ACTION="${2:-print}"
shift 2 || true

usage() {
  cat <<'EOF'
nando phase-center client env

Usage:
  nando-phase-center-client-env.sh /etc/nando-wave/phase-center.env print
  nando-phase-center-client-env.sh /etc/nando-wave/phase-center.env status
  nando-phase-center-client-env.sh /etc/nando-wave/phase-center.env install-user [PATH]
  nando-phase-center-client-env.sh /etc/nando-wave/phase-center.env install-system [PATH] [--allow-canary-only]

Purpose:
  Emit or install a sanitized client env for local agent windows.

Boundary:
  This helper never prints provider secrets and never writes upstream API keys.
  It only publishes the local OpenAI-compatible bridge URL and local canary key.

Safety:
  install-system is blocked until broad provider traffic is ready, unless the
  operator explicitly passes --allow-canary-only for a local lab canary.
EOF
}

if [[ "${ENV_FILE}" == "--help" || "${ENV_FILE}" == "-h" || "${ACTION}" == "--help" || "${ACTION}" == "-h" ]]; then
  usage
  exit 0
fi

BIND="127.0.0.1:8787"
if [[ -r "${ENV_FILE}" ]]; then
  set -a
  # shellcheck disable=SC1090
  . "${ENV_FILE}"
  set +a
  BIND="${NANDO_PROVIDER_BRIDGE_BIND:-${BIND}}"
fi

BASE_URL="http://${BIND}/v2"
BASE_URL_V1="http://${BIND}/v1"
BASE_URL_V2="http://${BIND}/v2"
BRIDGE_URL="http://${BIND}"
DEFAULT_USER_HOME="${HOME:-}"
if [[ -z "${DEFAULT_USER_HOME}" ]]; then
  DEFAULT_USER_HOME="$(getent passwd "$(id -un)" 2>/dev/null | cut -d: -f6 || true)"
fi
if [[ -z "${DEFAULT_USER_HOME}" ]]; then
  DEFAULT_USER_HOME="/tmp"
fi
if [[ -n "${SUDO_USER:-}" && "${SUDO_USER}" != "root" ]]; then
  sudo_home="$(getent passwd "${SUDO_USER}" 2>/dev/null | cut -d: -f6 || true)"
  if [[ -n "${sudo_home}" ]]; then
    DEFAULT_USER_HOME="${sudo_home}"
  fi
fi
DEFAULT_USER_PATH="${DEFAULT_USER_HOME}/.config/nando-wave/client.env"
DEFAULT_SYSTEM_PATH="/etc/profile.d/nando-wave-client.sh"
UPSTREAM_READINESS_REPORT="${NANDO_PROVIDER_BRIDGE_UPSTREAM_READINESS_REPORT:-${NANDO_METRICS_DIR:-/var/lib/nando-wave/streaming/metrics}/nando-phase-center.provider-bridge-upstream-readiness.json}"

client_env_content() {
  cat <<EOF
# Nando Wave sanitized client bridge env.
# Generated by nando-phase-center-client-env.sh.
# No provider secrets are stored here.
export OPENAI_BASE_URL=${BASE_URL}
export OPENAI_API_BASE=${BASE_URL}
export OPENAI_API_KEY=nando-local
export NANDO_PROVIDER_BRIDGE_URL=${BRIDGE_URL}
export NANDO_CPU_BRIDGE_URL=${BRIDGE_URL}
export NANDO_CPU_OPENAI_BASE_URL_V1=${BASE_URL_V1}
export NANDO_CPU_OPENAI_BASE_URL_V2=${BASE_URL_V2}
export NANDO_CPU_API_VERSION=v2
export NANDO_CLIENT_ENV_SOURCE=nando-phase-center-client-env-v1
EOF
}

write_env_file() {
  local path="$1"
  local mode="$2"
  mkdir -p "$(dirname "${path}")"
  tmp="$(mktemp)"
  client_env_content > "${tmp}"
  install -m "${mode}" "${tmp}" "${path}"
  rm -f "${tmp}"
}

upstream_readiness_value() {
  local field="$1"
  local fallback_jq="$2"
  local fallback_raw="$3"
  if [[ -s "${UPSTREAM_READINESS_REPORT}" ]] && jq -e . "${UPSTREAM_READINESS_REPORT}" >/dev/null 2>&1; then
    jq -r "${field} // ${fallback_jq}" "${UPSTREAM_READINESS_REPORT}" 2>/dev/null || printf '%s\n' "${fallback_raw}"
  else
    printf '%s\n' "${fallback_raw}"
  fi
}

print_status() {
  local user_path="${1:-${DEFAULT_USER_PATH}}"
  local system_path="${2:-${DEFAULT_SYSTEM_PATH}}"
  user_installed=false
  system_installed=false
  [[ -s "${user_path}" ]] && user_installed=true
  [[ -s "${system_path}" ]] && system_installed=true
  upstream_configured="$(upstream_readiness_value '.upstream_configured' 'false' 'false')"
  broad_ready="$(upstream_readiness_value '.ready_for_broad_provider_traffic' 'false' 'false')"
  upstream_verdict="$(upstream_readiness_value '.verdict' '"missing"' 'missing')"
  default_bridge_allowed=false
  default_bridge_blocker="broad_provider_traffic_not_ready"
  if [[ "${broad_ready}" == "true" ]]; then
    default_bridge_allowed=true
    default_bridge_blocker="none"
  fi
  jq -n \
    --arg env_file "${ENV_FILE}" \
    --arg bind "${BIND}" \
    --arg base_url "${BASE_URL}" \
    --arg bridge_url "${BRIDGE_URL}" \
    --arg upstream_readiness_report "${UPSTREAM_READINESS_REPORT}" \
    --arg upstream_verdict "${upstream_verdict}" \
    --arg default_bridge_blocker "${default_bridge_blocker}" \
    --arg user_path "${user_path}" \
    --arg system_path "${system_path}" \
    --argjson user_installed "${user_installed}" \
    --argjson system_installed "${system_installed}" \
    --argjson upstream_configured "${upstream_configured}" \
    --argjson broad_provider_traffic_ready "${broad_ready}" \
    --argjson default_bridge_allowed "${default_bridge_allowed}" \
    '{
      report_kind: "nando_phase_center_client_env_status_v1",
      env_file: $env_file,
      bridge_bind: $bind,
      openai_base_url: $base_url,
      default_api_version: "v2",
      bridge_url: $bridge_url,
      upstream_readiness_report: $upstream_readiness_report,
      upstream_verdict: $upstream_verdict,
      upstream_configured: $upstream_configured,
      broad_provider_traffic_ready: $broad_provider_traffic_ready,
      default_bridge_allowed: $default_bridge_allowed,
      default_bridge_blocker: $default_bridge_blocker,
      local_api_key_value: "nando-local",
      provider_secret_printed: false,
      provider_secret_stored: false,
      user_env_path: $user_path,
      user_env_installed: $user_installed,
      system_env_path: $system_path,
      system_env_installed: $system_installed,
      boundary: "sanitized client env only: no provider upstream secret, no local_accept policy mutation, no mining, no scoring"
    }'
}

case "${ACTION}" in
  print)
    client_env_content
    ;;
  status)
    print_status
    ;;
  install-user)
    path="${1:-${DEFAULT_USER_PATH}}"
    write_env_file "${path}" "0600"
    print_status "${path}" "${DEFAULT_SYSTEM_PATH}"
    ;;
  install-system)
    path="${DEFAULT_SYSTEM_PATH}"
    allow_canary_only=0
    while [[ "$#" -gt 0 ]]; do
      case "$1" in
        --allow-canary-only)
          allow_canary_only=1
          shift
          ;;
        *)
          path="$1"
          shift
          ;;
      esac
    done
    if [[ "${EUID}" -ne 0 ]]; then
      echo "install-system requires root; run with sudo" >&2
      exit 2
    fi
    broad_ready="$(upstream_readiness_value '.ready_for_broad_provider_traffic' 'false' 'false')"
    if [[ "${broad_ready}" != "true" && "${allow_canary_only}" != "1" ]]; then
      print_status "${DEFAULT_USER_PATH}" "${path}" >&2
      echo "install-system blocked: broad provider traffic is not ready; pass --allow-canary-only only for a reviewed local lab canary" >&2
      exit 3
    fi
    write_env_file "${path}" "0644"
    print_status "${DEFAULT_USER_PATH}" "${path}"
    ;;
  *)
    echo "unknown action: ${ACTION}" >&2
    usage >&2
    exit 2
    ;;
esac
